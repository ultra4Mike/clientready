import { needsCoSignature, coSignatureBanner, isChangeOrder } from "@/lib/co-signature";
let fails = 0; const ok = (c: boolean, m: string) => { if (!c) fails++; console.log((c ? "ok " : "FAIL ") + m); };
const sig = { type: "typed", text: "Pat Lee", signerName: "Pat Lee", signedAt: "2026-10-20T15:00:00Z" };
const a = { id: "a", type: "invoice", data: { invoiceNumber: "INV-1", status: "sent", signature: sig } };
const rev = (extra: Record<string, unknown>) => ({ id: "r", type: "invoice", data: { invoiceNumber: "INV-2", coMode: "revision", revises: { id: "a", number: "INV-1" }, changeOrderOf: { id: "a", number: "INV-1" }, status: "sent", ...extra } });
ok(isChangeOrder(rev({})) && !isChangeOrder(a), "detects change orders");
ok(!needsCoSignature(rev({ status: "draft" })), "draft: no flag");
ok(!needsCoSignature(rev({ status: "void" })), "void: no flag");
ok(needsCoSignature(rev({})), "sent unsigned: flag");
ok(!needsCoSignature(rev({ signature: sig })), "signed: cleared");
ok(!needsCoSignature(rev({ approval: { status: "approved", approvedAt: "2026-10-22T10:00:00Z", approverName: "Pat" } })), "approved: cleared");
ok(needsCoSignature(rev({ approval: { status: "pending", createdAt: "x" } })), "pending approval: still flagged");
ok(!needsCoSignature(a), "plain invoice never flagged");
const b = coSignatureBanner([a, rev({})], rev({}));
ok(b === "Needs customer signature: the previous version was signed by Pat Lee on Oct 20, 2026, so this change needs a new approval", b);
const unsignedA = { ...a, data: { ...a.data, signature: null } };
ok(coSignatureBanner([unsignedA, rev({})], rev({})) === "Needs customer signature", "unsigned prior: short text");
const addOn = { id: "c", type: "invoice", data: { invoiceNumber: "INV-3", status: "sent", changeOrderOf: { id: "a", number: "INV-1" } } };
ok(needsCoSignature(addOn) && /Pat Lee/.test(coSignatureBanner([a, addOn], addOn)), "add-on change order flagged too");
if (fails) { console.log(fails + " failed"); process.exit(1); } else console.log("all passed");
